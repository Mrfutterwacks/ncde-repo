#!/usr/bin/env bash
# ncde-chromium-sync.sh — point Chromium's livery at NCDE's current mode.
# Called by the engine whenever ncde.darkMode flips (and once at login).
#
# It does three things:
#   1. selects the matching NCDE Chromium theme (day / night chrome),
#   2. sets the freedesktop portal colour-scheme so web pages' prefers-color-scheme
#      follows NCDE (the gentle, per-site-respecting route),
#   3. optionally enables --force-dark-mode for web CONTENT (the hammer) when the
#      user has asked for it (NCDE setting: chromiumForceDark).
#
# Usage:  ncde-chromium-sync.sh [dark|light]
#         (no arg → reads ~/.config/ncde/active-theme.json)

set -euo pipefail
THEMES_DIR="${NCDE_CHROMIUM_THEMES:-/usr/share/ncde/chromium}"
CFG="$HOME/.config/ncde"
ACTIVE="$CFG/active-theme.json"
STATE="$CFG/chromium-theme"          # remembers the loaded theme dir for the launcher

mode="${1:-}"
if [[ -z "$mode" ]]; then
  # 2026-07-11 fix: the engine writes `"mode": "dark"` in active-theme.json —
  # no "darkMode" key exists there. The old grep for `"darkMode": true` never
  # matched, so every no-arg call (= every Chromium launch via the wrapper)
  # fell through to mode=light and un-darked the whole desktop (theme-day +
  # gsettings prefer-light) until the engine next reapplied.
  if grep -q '"mode"[[:space:]]*:[[:space:]]*"dark"' "$ACTIVE" 2>/dev/null; then
    mode="dark"; else mode="light"; fi
fi

# 1) chrome theme → record which unpacked theme the launcher should load
if [[ "$mode" == "dark" ]]; then
  echo "$THEMES_DIR/theme-night" > "$STATE"
else
  echo "$THEMES_DIR/theme-day" > "$STATE"
fi

# 2) portal colour-scheme → web prefers-color-scheme follows NCDE
#    (modern Chromium reads org.freedesktop.appearance via xdg-desktop-portal)
if command -v gsettings >/dev/null 2>&1; then
  if [[ "$mode" == "dark" ]]; then
    gsettings set org.gnome.desktop.interface color-scheme 'prefer-dark' || true
  else
    gsettings set org.gnome.desktop.interface color-scheme 'prefer-light' || true
  fi
fi

# 3) write the launch flags file the wrapper sources
# Chromium keeps only the LAST --enable-features switch — two lines meant the
# WebContentsForceDark line silently dropped WebUIDarkMode. Build ONE merged
# feature list and emit a single switch.
FLAGS="$CFG/chromium-flags.conf"
features="WebUIDarkMode"
forcedark=""
if [[ "$mode" == "dark" ]]; then
  # GLOBAL page dark is the NCDE default (easier on the eyes). It darkens
  # backgrounds/text but, via image_behavior/selective, leaves photos and
  # already-dark images alone so they don't look like negatives.
  # Opt OUT by setting "chromiumForceDark": false in active-theme.json — then
  # only sites with their own dark mode follow, via prefers-color-scheme.
  if grep -q '"chromiumForceDark"[[:space:]]*:[[:space:]]*false' "$ACTIVE" 2>/dev/null; then
    : # polite mode — prefers-color-scheme only
  else
    forcedark="--force-dark-mode"
    features="$features,WebContentsForceDark:inversion_method/cielab_based/image_behavior/selective/foreground_lightness_threshold/150/background_lightness_threshold/205"
  fi
fi
{
  echo "# generated by ncde-chromium-sync.sh — do not edit by hand"
  [[ -n "$forcedark" ]] && echo "$forcedark"
  echo "--enable-features=$features"
} > "$FLAGS"

# nudge a running Chromium to re-read the theme: the chrome theme only applies
# on (re)launch, so we just report — NCDE shows a toast offering to relaunch.
echo "ncde-chromium: mode=$mode  theme=$(cat "$STATE")"
